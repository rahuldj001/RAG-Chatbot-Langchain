"""Configuration schemas for the RAG pipeline using Pydantic.

Centralizes hyperparameters for:
1. LLM / Ollama settings (sampling temperature, context window, token memory)
2. Hybrid Retriever settings (fusion weights, query expansion, top-k, reranking model)
3. Ingestion settings (chunk size, overlap, embedding model, cache directory)
4. Vector Storage settings (persistence directories, collection names)
"""

from pydantic import BaseModel, Field
from typing import List


class OllamaSettings(BaseModel):
    """Hyperparameters and connection configuration for LLM generation."""
    llm: str = Field(default="openai/gpt-oss-20b", description="Default LLM model name")
    keep_alive: str = Field(default="1h", description="How long Ollama keeps model in memory")
    tfs_z: float = Field(default=1.0, description="Tail Free Sampling factor (reduces low-probability tokens)")
    top_k: int = Field(default=40, description="Top-k tokens considered during generation")
    top_p: float = Field(default=0.9, description="Nucleus sampling threshold")
    repeat_last_n: int = Field(default=64, description="Lookback window to penalize repeated phrases")
    repeat_penalty: float = Field(default=1.1, description="Penalty multiplier for repeated tokens")
    request_timeout: float = Field(default=300, description="API request timeout in seconds")
    port: int = Field(default=11434, description="Default Ollama HTTP port")
    context_window: int = Field(default=8000, description="Max token context window for the model")
    temperature: float = Field(default=0.1, description="Low temperature (0.1) for deterministic factual answers")
    chat_token_limit: int = Field(default=4000, description="Max conversational history tokens preserved in memory")


class RetrieverSettings(BaseModel):
    """Hyperparameters for two-stage hybrid retrieval (BM25 keyword + Dense Vector)."""
    num_queries: int = Field(default=5, description="Number of variations generated by LLM for query expansion")
    similarity_top_k: int = Field(default=20, description="Candidate chunks retrieved before reranking")
    retriever_weights: List[float] = Field(
        default=[0.4, 0.6], description="Weights assigned to [BM25 sparse score, Dense vector similarity]"
    )
    top_k_rerank: int = Field(default=6, description="Final top chunks kept after cross-encoder reranking")
    rerank_llm: str = Field(
        default="BAAI/bge-reranker-base", description="Cross-encoder model used for accurate chunk re-scoring"
    )
    fusion_mode: str = Field(default="dist_based_score", description="Reciprocal rank fusion or distance scoring algorithm")


class IngestionSettings(BaseModel):
    """Document parsing, text splitting, and embedding generation settings."""
    embed_llm: str = Field(
        default="BAAI/bge-small-en-v1.5", description="Dense embedding model (CPU-friendly and lightweight)"
    )
    embed_batch_size: int = Field(default=8, description="Number of text chunks embedded per inference batch")
    cache_folder: str = Field(default="data/huggingface", description="Local folder to cache HuggingFace model weights")
    chunk_size: int = Field(default=512, description="Target chunk size in tokens/characters for text splitter")
    chunk_overlap: int = Field(default=32, description="Sliding overlap between consecutive chunks to retain context")
    chunking_regex: str = Field(
        default="[^,.;。？！]+[,.;。？！]?", description="Sentence boundary regex for document tokenization"
    )
    paragraph_sep: str = Field(default="\n \n", description="Separator used to split raw paragraphs")
    num_workers: int = Field(default=0, description="Worker threads for parallel document parsing")


class StorageSettings(BaseModel):
    """File storage and vector database persistence configuration."""
    persist_dir_chroma: str = Field(
        default="data/chroma", description="Path to persist ChromaDB index data"
    )
    persist_dir_storage: str = Field(
        default="data/storage", description="Path to store file indexes and docstores"
    )
    collection_name: str = Field(default="collection", description="Default Chroma vector collection name")
    port: int = Field(default=8000, description="Vector store service port (if using client-server mode)")


class RAGSettings(BaseModel):
    """Root configuration aggregating all sub-component settings."""
    ollama: OllamaSettings = OllamaSettings()
    retriever: RetrieverSettings = RetrieverSettings()
    ingestion: IngestionSettings = IngestionSettings()
    storage: StorageSettings = StorageSettings()
